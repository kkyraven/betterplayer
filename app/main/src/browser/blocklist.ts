export function isBlockedHost(host: string): boolean {
  let name = host.toLowerCase()
  for (;;) {
    if (BLOCKED.has(name)) return true
    const dot = name.indexOf('.')
    if (dot < 0) return false
    name = name.slice(dot + 1)
    if (!name.includes('.')) return false
  }
}
